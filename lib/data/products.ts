function mulberry32(seed: number) {
  let a = seed;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function buildHistory(options: {
  endPrice: number;
  startPrice: number;
  days: number;
  seed: number;
  dipAtEnd?: boolean;
}): PricePoint[] {
  const { endPrice, startPrice, days, seed, dipAtEnd = false } = options;
  const rand = mulberry32(seed);
  const points: PricePoint[] = [];
  const today = new Date();
  today.setHours(0, 0, 0, 0);

  for (let i = days - 1; i >= 0; i--) {
    const progress = (days - 1 - i) / (days - 1);
    const base = startPrice + (endPrice - startPrice) * progress;
    const noise = (rand() - 0.5) * (startPrice * 0.018);
    let price = Math.round((base + noise) / 10) * 10;

    if (dipAtEnd && i < 6) {
      const extra = ((6 - i) / 6) * (endPrice - price);
      price = Math.round((price + extra) / 10) * 10;
    }

    if (i === 0) price = endPrice;

    const date = new Date(today);
    date.setDate(today.getDate() - i);
    points.push({
      date: date.toISOString().slice(0, 10),
      price: Math.max(price, endPrice),
    });
  }

  return points;
}

function offer(storeId: string, price: number, url: string, daysAgo = 0): StoreOffer {
  const updated = new Date();
  updated.setDate(updated.getDate() - daysAgo);
  return {
    storeId,
    price,
    url,
    updatedAt: updated.toISOString(),
    inStock: true,
    source: "demo",
  };
}

